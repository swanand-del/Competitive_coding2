# Sum of first n numbers
n = int(input("Enter number: "))
sum = 0
i = 1

while i <= n:
    sum = sum + i
    i = i + 1

print("The sum of first", n, "numbers is:", sum)


# Remove duplicate characters from string
name = "prashant"
result = ""

for i in name:
    if i not in result:
        result += i

print(name)
