# Linear Search Function
# -------------------------------

mylist = [1, 4, 5, 2, 7, 9]

def search(target, mylist):
    for i in mylist:
        if i == target:
            print("Found target:", i)
            return i
    return -1


tar = int(input("Enter number to search: "))
ans = search(tar, mylist)
print(ans)